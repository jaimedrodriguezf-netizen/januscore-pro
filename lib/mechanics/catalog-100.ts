/**
 * Return list of all unique brands in the master catalog.
 */
export function getAvailableBrands(): string[] {
  const brands = Array.from(new Set(MASTER_VEHICLE_CATALOG.map((v) => v.brand)));
  return brands.sort();
}

/**
 * Return list of all models for a specific brand.
 */
export function getModelsByBrand(brand: string): string[] {
  return MASTER_VEHICLE_CATALOG.filter(
    (v) => v.brand.toLowerCase() === brand.toLowerCase()
  ).map((v) => v.model);
}

/**
 * Find maintenance template by brand and model name.
 */
export function findMaintenanceTemplate(
  brand: string,
  model: string
): MaintenanceTemplate | undefined {
  const b = brand.toLowerCase().trim();
  const m = model.toLowerCase().trim();

  return MASTER_VEHICLE_CATALOG.find(
    (v) =>
      v.brand.toLowerCase() === b &&
      (v.model.toLowerCase() === m ||
        v.model.toLowerCase().includes(m) ||
        m.includes(v.model.toLowerCase().split(' ')[0]))
  );
}
